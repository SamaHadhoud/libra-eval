"""
generate_latex.py — emits every number and table of the K2-V3 family report as
LaTeX fragments under family_report/generated/. The report's .tex only \\inputs
fragments and references \\famnum{<model_key>}{<stat>} macros, so no result
number is ever typed by hand.

Run:  .venv/bin/python family_report/generate_latex.py
Rerun whenever models.json gains a model or a results dir changes.

Emitted files (all under generated/):
  preamble.tex        \\famnum accessor + \\task macro — \\input once in the preamble
  numbers.tex         every stat as a \\famnum register — \\input after preamble.tex
  tab_overview.tex    domains x models mean-score table
  tab_dom_<sec>.tex   per-domain task table, one score column per model
  tab_full.tex        appendix longtable: all main tasks x models
  tab_uae.tex         UAE tasks: family models + baselines
  tab_multilingual.tex
  tab_movers.tex      largest per-task deltas smallest->largest (>=2 models only)
  figs.tex            figure environments for the generate_family.py charts

Required packages in the consuming document:
  booktabs, longtable, array, graphicx, float
"""
from __future__ import annotations

import datetime
import os
import re

import family_lib as F
from family_lib import FamilyData, fmt

L = F.L
OUT = F.GENERATED
os.makedirs(OUT, exist_ok=True)

HEADER = "%% AUTO-GENERATED by family_report/generate_latex.py — do not edit.\n"


def write(name: str, body: str):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(HEADER + body)
    print(f"  wrote generated/{name}")


def esc(s: str) -> str:
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def meaning(s: str) -> str:
    return s.replace("_", "-")


ATTACK_SHORT = {"direct_risky": "direct", "instruction_hierarchy": "instr-hierarchy",
                "over_sensitive": "over-sensitive"}


def attack_short(s: str) -> str:
    return ATTACK_SHORT.get(s, s.replace("_", "-"))


# --------------------------------------------------------------------------- #
# preamble.tex
# --------------------------------------------------------------------------- #
def gen_preamble():
    write("preamble.tex", r"""
% \famnum{<model_key>}{<stat>} — expands to a number generated from the eval
% results. Keys/stats are defined in numbers.tex; unknown lookups error loudly.
\newcommand{\famnum}[2]{%
  \ifcsname famnum@#1@#2\endcsname
    \csname famnum@#1@#2\endcsname
  \else
    \errmessage{famnum: no stat '#2' for model '#1' (regenerate numbers.tex?)}%
  \fi}
% task names: typewriter, escaped underscores that allow line breaks
\providecommand{\task}[1]{{\ttfamily\small\def\_{\textunderscore\allowbreak}#1}}
""".lstrip())


