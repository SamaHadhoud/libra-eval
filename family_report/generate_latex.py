# numbers.tex
# --------------------------------------------------------------------------- #
def gen_numbers(fd: FamilyData):
    lines = []

    def put(key: str, stat: str, val):
        stat = re.sub(r"[^a-zA-Z0-9_]", "", stat)
        lines.append(
            f"\\expandafter\\gdef\\csname famnum@{key}@{stat}\\endcsname{{{val}}}")

    for e in fd.family:
        a = e.agg
        put(e.key, "label", esc(e.label))
        put(e.key, "size_b", "--" if e.size_b is None else f"{e.size_b:g}")
        put(e.key, "mean_main", fmt(a["mean_score"]))
        put(e.key, "median_main", fmt(a["median_score"]))
        put(e.key, "min_main", fmt(a["min_score"]))
        put(e.key, "max_main", fmt(a["max_score"]))
        put(e.key, "n_main_tasks", a["n_main_tasks"])
        put(e.key, "n_samples", f"{a['n_total_samples']:,}")
        put(e.key, "n_ge095", a["n_ge_095"])
        put(e.key, "n_lt080", a["n_lt_080"])
        put(e.key, "safety_rate", f"{a['weighted_safety'] * 100:.1f}")
        put(e.key, "mean_ci",
            fmt(F.mean_se(e, [t for t in fd.main_tasks if t in e.tasks])))
        for sec in F.SECTION_ORDER:
            put(e.key, f"dom_{sec}", fmt(fd.section_mean(e, sec)))
            put(e.key, f"dom_{sec}_n", len([n for n in fd.section_tasks(sec)
                                            if n in e.tasks]))
        for tn in fd.uae_tasks() + fd.multilingual_tasks():
            s = fd.score(e, tn)
            if s is not None:
                put(e.key, f"task_{tn}", fmt(s))
    for e in fd.baselines:
        put(e.key, "label", esc(e.label))
        for tn in fd.uae_tasks():
            s = fd.score(e, tn)
            if s is not None:
                put(e.key, f"task_{tn}", fmt(s))
    for e in fd.comparisons:
        a = e.agg
        put(e.key, "label", esc(e.label))
        if a:
            put(e.key, "mean_main", fmt(a["mean_score"]))
            put(e.key, "safety_rate", f"{a['weighted_safety'] * 100:.1f}")
            for sec in F.SECTION_ORDER:
                put(e.key, f"dom_{sec}", fmt(fd.section_mean(e, sec)))

    put("family", "n_models", len(fd.family))
    put("family", "n_tasks", len(fd.main_tasks))
    put("family", "model_list", esc(", ".join(e.label for e in fd.family)))
    put("family", "generated_date", datetime.date.today().isoformat())
    if len(fd.family) >= 2:
        small, large = fd.family[0], fd.family[-1]
        put("family", "delta_mean",
            f"{large.agg['mean_score'] - small.agg['mean_score']:+.3f}")
    write("numbers.tex", "\n".join(lines) + "\n")


