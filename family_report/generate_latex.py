def _model_heads(models) -> str:
    return " & ".join(f"\\textbf{{{esc(e.label)}}}" for e in models)


def gen_overview(fd: FamilyData):
    cols = "l r " + "r " * len(fd.family)
    rows = []
    for sec in F.SECTION_ORDER:
        title = esc(L.SECTIONS[sec]["title"])
        n = len(fd.section_tasks(sec))
        cells = " & ".join(fmt(fd.section_mean(e, sec)) for e in fd.family)
        rows.append(f"{title} & {n} & {cells}\\\\")
    overall = " & ".join(fmt(e.agg["mean_score"]) for e in fd.family)
    body = "\n".join(rows)
    write("tab_overview.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Mean score by safety domain across the K2-V3 family (higher is better).}}
\\label{{tab:fam-overview}}
\\begin{{tabular}}{{@{{}}{cols}@{{}}}}
\\toprule
\\textbf{{Domain}} & \\textbf{{Tasks}} & {_model_heads(fd.family)}\\\\
\\midrule
{body}
\\midrule
\\textbf{{Overall (main suite)}} & {len(fd.main_tasks)} & {overall}\\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def _task_rows(fd: FamilyData, tasks: list[str], models) -> str:
    rows = []
    for tn in tasks:
        m, attack, n = fd.task_meta(tn)
        cells = " & ".join(fmt(fd.score(e, tn)) for e in models)
        rows.append(f"\\task{{{esc(tn)}}} & {meaning(m)} & {n} & {attack_short(attack)} & {cells}\\\\")
    return "\n".join(rows)


def gen_domain_tables(fd: FamilyData):
    for sec in F.SECTION_ORDER:
        tasks = fd.section_tasks(sec)
        if not tasks:
            continue
        title = esc(L.SECTIONS[sec]["title"])
        cols = ">{\\raggedright\\arraybackslash}p{4.6cm} l r l " + "r " * len(fd.family)
        write(f"tab_dom_{sec}.tex", f"""
\\begin{{table}}[t]\\centering\\footnotesize
\\caption{{{title}: per-task scores.}}
\\label{{tab:fam-dom-{sec.replace('_', '-')}}}
\\begin{{tabular}}{{@{{}}{cols}@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Metric}} & \\textbf{{$n$}} & \\textbf{{Attack}} & {_model_heads(fd.family)}\\\\
\\midrule
{_task_rows(fd, tasks, fd.family)}
\\midrule
\\textbf{{Domain mean}} & & & & {" & ".join(fmt(fd.section_mean(e, sec)) for e in fd.family)}\\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_full_table(fd: FamilyData):
    cols = ">{\\raggedright\\arraybackslash}p{4.6cm} l r " + "r " * len(fd.family)
    head = (f"\\textbf{{Dataset}} & \\textbf{{Metric}} & \\textbf{{$n$}} & "
            f"{_model_heads(fd.family)}\\\\")
    chunks = []
    ncol = 3 + len(fd.family)
    for sec in F.SECTION_ORDER:
        tasks = fd.section_tasks(sec)
        if not tasks:
            continue
        chunks.append(f"\\multicolumn{{{ncol}}}{{@{{}}l}}"
                      f"{{\\textbf{{{esc(L.SECTIONS[sec]['title'])}}}}}\\\\*")
        for tn in tasks:
            m, _, n = fd.task_meta(tn)
            cells = " & ".join(fmt(fd.score(e, tn)) for e in fd.family)
            chunks.append(f"\\task{{{esc(tn)}}} & {meaning(m)} & {n} & {cells}\\\\")
        chunks.append("\\midrule")
    if chunks and chunks[-1] == "\\midrule":
        chunks.pop()
    body = "\n".join(chunks)
    write("tab_full.tex", f"""
\\footnotesize
\\begin{{longtable}}{{@{{}}{cols}@{{}}}}
\\caption{{Full main-suite results across the K2-V3 family.}}
\\label{{tab:fam-full}}\\\\
\\toprule
{head}
\\midrule
\\endfirsthead
\\toprule
{head}
\\midrule
\\endhead
\\bottomrule
\\endlastfoot
{body}
\\end{{longtable}}
\\normalsize
""".lstrip())


def gen_uae_multiling(fd: FamilyData):
    models = fd.family + fd.comparisons + [
        b for b in fd.baselines
        if any(fd.score(b, t) is not None for t in fd.uae_tasks())]
    cols = (">{\\raggedright\\arraybackslash}p{3.2cm} "
            ">{\\raggedright\\arraybackslash}p{2.1cm} " + "r " * len(models))
    write("tab_uae.tex", f"""
\\begin{{table}}[t]\\centering\\footnotesize
\\caption{{UAE-specific benchmarks: K2-V3 family vs.\\ prior version(s) and baseline.}}
\\label{{tab:fam-uae}}
\\begin{{tabular}}{{@{{}}{cols}@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Metric}} & {_model_heads(models)}\\\\
\\midrule
{chr(10).join(
    f"\\task{{{esc(tn)}}} & {meaning(fd.task_meta(tn)[0])} & "
    + " & ".join(fmt(fd.score(e, tn)) for e in models) + "\\\\"
    for tn in fd.uae_tasks())}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())

    ml_models = fd.family + fd.comparisons
    cols = (">{\\raggedright\\arraybackslash}p{3.2cm} "
            ">{\\raggedright\\arraybackslash}p{2.1cm} " + "r " * len(ml_models))
    write("tab_multilingual.tex", f"""
\\begin{{table}}[t]\\centering\\footnotesize
\\caption{{Multilingual safety (exploratory; outside the main aggregates).}}
\\label{{tab:fam-multilingual}}
\\begin{{tabular}}{{@{{}}{cols}@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Metric}} & {_model_heads(ml_models)}\\\\
\\midrule
{chr(10).join(
    f"\\task{{{esc(tn)}}} & {meaning(fd.task_meta(tn)[0])} & "
    + " & ".join(fmt(fd.score(e, tn)) for e in ml_models) + "\\\\"
    for tn in fd.multilingual_tasks())}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_comparison(fd: FamilyData):
    """Version comparison: the anchor (largest family model) vs each comparison
    model, by domain + overall. Emits an empty stub if no comparisons."""
    if not fd.comparisons:
        write("tab_comparison.tex", "% no comparison models in models.json.\n")
        write("tab_comparison_movers.tex", "% no comparison models in models.json.\n")
        return
    anchor = fd.anchor
    cols = fd.comparisons
    models = [anchor] + cols
    body = []
    for sec in F.SECTION_ORDER:
        cells = " & ".join(fmt(fd.section_mean(e, sec)) for e in models)
        body.append(f"{esc(L.SECTIONS[sec]['title'])} & {cells}\\\\")
    overall = " & ".join(fmt(e.agg['mean_score']) if e.agg else "--" for e in models)
    write("tab_comparison.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Version comparison: {esc(anchor.label)} vs.\\ prior version(s), mean score by domain.}}
\\label{{tab:fam-comparison}}
\\begin{{tabular}}{{@{{}}l {"r " * len(models)}@{{}}}}
\\toprule
\\textbf{{Domain}} & {_model_heads(models)}\\\\
\\midrule
{chr(10).join(body)}
\\midrule
\\textbf{{Overall (main suite)}} & {overall}\\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())

    # movers: anchor vs first comparison, largest per-task deltas
    comp = cols[0]
    deltas = []
    for tn in fd.main_tasks:
        a, b = fd.score(anchor, tn), fd.score(comp, tn)
        if a is not None and b is not None:
            deltas.append((tn, a, b, a - b))
    deltas.sort(key=lambda r: -abs(r[3]))
    rows = "\n".join(
        f"\\task{{{esc(tn)}}} & {fmt(a)} & {fmt(b)} & {d:+.3f}\\\\"
        for tn, a, b, d in deltas[:15])
    write("tab_comparison_movers.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Largest per-task differences, {esc(anchor.label)} vs.\\ {esc(comp.label)} ($\\Delta$ = anchor $-$ prior).}}
\\label{{tab:fam-comparison-movers}}
\\begin{{tabular}}{{@{{}}>{{\\raggedright\\arraybackslash}}p{{5.2cm}} r r r@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{{esc(anchor.label)}}} & \\textbf{{{esc(comp.label)}}} & \\textbf{{$\\Delta$}}\\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_runhealth(fd: FamilyData):
    """Data-quality table: a model whose endpoint dropped prompts must not
    look identical to a clean run."""
    rows = []
    for e in fd.family:
        h = F.run_health(e, fd.main_tasks)
        rows.append(f"{esc(e.label)} & {h['n_tasks']} & {h['n_missing']} & "
                    f"{h['n_samples']:,} & {h['n_ambig_err']}\\\\")
    write("tab_runhealth.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Run health / data quality (main suite).}}
\\label{{tab:fam-runhealth}}
\\begin{{tabular}}{{@{{}}l r r r r@{{}}}}
\\toprule
\\textbf{{Model}} & \\textbf{{Tasks}} & \\textbf{{Missing}} & \\textbf{{Samples judged}} & \\textbf{{Ambig./error}}\\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_axis_means(fd: FamilyData):
    """Mean per score_meaning axis — the defensible split behind the blended
    overall mean (safety-refusal vs compliance vs accuracy are not one axis)."""
    axes = sorted({ax for e in fd.family for ax in F.axis_means(e)})
    per = {e.key: F.axis_means(e) for e in fd.family}
    rows = []
    for ax_name in axes:
        ns = {per[e.key].get(ax_name, (None, 0))[1] for e in fd.family}
        ntasks = max(ns)
        cells = " & ".join(fmt(per[e.key].get(ax_name, (None, 0))[0])
                           for e in fd.family)
        rows.append(f"{meaning(ax_name)} & {ntasks} & {cells}\\\\")
    write("tab_axis_means.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Mean score by metric axis (main suite): the blended overall mean
mixes these; they are not interchangeable.}}
\\label{{tab:fam-axis-means}}
\\begin{{tabular}}{{@{{}}l r {"r " * len(fd.family)}@{{}}}}
\\toprule
\\textbf{{Metric axis}} & \\textbf{{Tasks}} & {_model_heads(fd.family)}\\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_anomalies(fd: FamilyData):
    """Non-monotonic-scaling tasks beyond CI noise — the read-these-first list."""
    an = F.scaling_anomalies(fd)
    if len(fd.family) < 3:
        write("tab_anomalies.tex",
              "% needs >=3 family models for non-monotonicity — regenerate then.\n")
        return
    if not an:
        write("tab_anomalies.tex",
              "% no scaling anomalies beyond CI noise — nothing to report.\n")
        return
    heads = " & ".join(f"\\textbf{{{esc(e.label)}}}" for e in fd.family)
    rows = "\n".join(
        f"\\task{{{esc(r['task'])}}} & "
        + " & ".join(fmt(s) for s in r["scores"])
        + f" & {fmt(r['amplitude'])}\\\\"
        for r in an[:15])
    write("tab_anomalies.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Scaling anomalies: tasks whose score is non-monotonic in model size
beyond 95\\%-CI noise (read these first).}}
\\label{{tab:fam-anomalies}}
\\begin{{tabular}}{{@{{}}>{{\\raggedright\\arraybackslash}}p{{4.6cm}} {"r " * len(fd.family)}r@{{}}}}
\\toprule
\\textbf{{Dataset}} & {heads} & \\textbf{{Amplitude}}\\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


def gen_movers(fd: FamilyData):
    if len(fd.family) < 2:
        write("tab_movers.tex",
              "% needs >=2 family models in models.json — regenerate then.\n")
        return
    small, large = fd.family[0], fd.family[-1]
    deltas = []
    for tn in fd.main_tasks:
        a, b = fd.score(small, tn), fd.score(large, tn)
        if a is not None and b is not None:
            deltas.append((tn, a, b, b - a))
    deltas.sort(key=lambda r: -abs(r[3]))
    rows = "\n".join(
        f"\\task{{{esc(tn)}}} & {fmt(a)} & {fmt(b)} & {d:+.3f}\\\\"
        for tn, a, b, d in deltas[:15])
    write("tab_movers.tex", f"""
\\begin{{table}}[t]\\centering\\small
\\caption{{Largest per-task score changes, {esc(small.label)} $\\rightarrow$ {esc(large.label)}.}}
\\label{{tab:fam-movers}}
\\begin{{tabular}}{{@{{}}>{{\\raggedright\\arraybackslash}}p{{5.4cm}} r r r@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{{esc(small.label)}}} & \\textbf{{{esc(large.label)}}} & \\textbf{{$\\Delta$}}\\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".lstrip())


